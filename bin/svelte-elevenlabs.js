#!/usr/bin/env node
/**
 * Install the svelte-elevenlabs agent guide into a consumer project.
 *
 * The command is intentionally dependency free so it runs with Node 22.17 or
 * newer and Bun 1.4 or newer. It writes only local Markdown files, never calls
 * the network, and never asks for an API key.
 */
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const KIT_ROOT = join(ROOT, 'agent-kit');
const GUIDE_PATH = join(KIT_ROOT, 'instructions.md');
const PACKAGE_PATH = join(ROOT, 'package.json');

const START_MARKER = '<!-- svelte-elevenlabs:agent-kit:start -->';
const END_MARKER = '<!-- svelte-elevenlabs:agent-kit:end -->';

const CLAUDE_DESCRIPTION =
	'Build or review Svelte 5 ElevenLabs Conversational AI voice and text sessions with the svelte-elevenlabs package. Use for ConversationWidget, AudioVisualizer, signed URL routes, client tools, and audio cleanup.';

/**
 * @typedef {'claude' | 'cursor' | 'opencode' | 'copilot' | 'windsurf' | 'cline' | 'gemini' | 'agents'} TargetName
 */

/**
 * @typedef {object} AgentTarget
 * @property {TargetName} name Stable name used on the command line.
 * @property {string} label Human readable tool name.
 * @property {string} path File path relative to the consumer project.
 * @property {boolean} shared Whether the file is shared with the project and must keep its content.
 * @property {string} [frontmatter] YAML frontmatter required by the tool.
 */

/** @type {AgentTarget[]} */
const TARGETS = [
	{
		name: 'claude',
		label: 'Claude Code',
		path: '.claude/skills/svelte-elevenlabs/SKILL.md',
		shared: false,
		frontmatter: `---\nname: svelte-elevenlabs\ndescription: ${CLAUDE_DESCRIPTION}\nlicense: MIT\n---\n\n`
	},
	{
		name: 'cursor',
		label: 'Cursor',
		path: '.cursor/rules/svelte-elevenlabs.mdc',
		shared: false,
		frontmatter: `---\ndescription: ${CLAUDE_DESCRIPTION}\nglobs: src/**/*.svelte, src/**/*.ts, src/**/*.js\nalwaysApply: false\n---\n\n`
	},
	{
		name: 'opencode',
		label: 'OpenCode',
		path: '.opencode/skills/svelte-elevenlabs/SKILL.md',
		shared: false,
		frontmatter: `---\nname: svelte-elevenlabs\ndescription: ${CLAUDE_DESCRIPTION}\nlicense: MIT\n---\n\n`
	},
	{
		name: 'copilot',
		label: 'GitHub Copilot',
		path: '.github/copilot-instructions.md',
		shared: true
	},
	{
		name: 'windsurf',
		label: 'Windsurf',
		path: '.windsurf/rules/svelte-elevenlabs.md',
		shared: false,
		frontmatter: `---\ntrigger: model_decision\ndescription: ${CLAUDE_DESCRIPTION}\nglobs: src/**/*.svelte, src/**/*.ts\n---\n\n`
	},
	{
		name: 'cline',
		label: 'Cline',
		path: '.clinerules/svelte-elevenlabs.md',
		shared: false
	},
	{
		name: 'gemini',
		label: 'Gemini CLI',
		path: 'GEMINI.md',
		shared: true
	},
	{
		name: 'agents',
		label: 'AGENTS.md aware tools',
		path: 'AGENTS.md',
		shared: true
	}
];

/** Aliases accepted on the command line. */
const ALIASES = new Map([
	['claude-code', 'claude'],
	['github-copilot', 'copilot'],
	['codex', 'agents'],
	['generic', 'agents']
]);

/** Error type used for expected command line failures. */
class AgentKitError extends Error {}

/**
 * Read the package version without assuming a JSON import attribute.
 *
 * @returns {string} Version from `package.json`.
 */
function readVersion() {
	try {
		const pkg = JSON.parse(readFileSync(PACKAGE_PATH, 'utf8'));
		return typeof pkg.version === 'string' ? pkg.version : '0.0.0';
	} catch {
		return '0.0.0';
	}
}

/**
 * Read the canonical agent guide.
 *
 * @returns {string} Guide body without a trailing newline.
 */
function readGuide() {
	if (!existsSync(GUIDE_PATH)) {
		throw new AgentKitError(
			`The agent guide is missing at ${GUIDE_PATH}. Reinstall svelte-elevenlabs and try again.`
		);
	}

	return readFileSync(GUIDE_PATH, 'utf8').trimEnd();
}

/**
 * Find one target by name or alias.
 *
 * @param {string} name Raw target name.
 * @returns {AgentTarget} Matching target.
 */
function findTarget(name) {
	const normalized = ALIASES.get(name) ?? name;
	const target = TARGETS.find((entry) => entry.name === normalized);
	if (!target) {
		throw new AgentKitError(
			`Unknown agent target "${name}". Use one of: ${TARGETS.map((entry) => entry.name).join(', ')}.`
		);
	}
	return target;
}

/**
 * Build the managed block for one target.
 *
 * @param {AgentTarget} target Target being rendered.
 * @param {string} guide Canonical guide body.
 * @param {string} version Package version.
 * @returns {string} Markdown block with start and end markers.
 */
function renderBlock(target, guide, version) {
	return `${START_MARKER}\n<!-- Generated by svelte-elevenlabs v${version}. Re-run the agents install command to update this block. -->\n\n${guide}\n${END_MARKER}`;
}

/**
 * Render the complete content for a target.
 *
 * @param {AgentTarget} target Target being rendered.
 * @param {string} guide Canonical guide body.
 * @param {string} version Package version.
 * @returns {string} Complete file content with a trailing newline.
 */
function renderTarget(target, guide, version) {
	const block = renderBlock(target, guide, version);
	const content = target.frontmatter ? `${target.frontmatter}${block}` : block;
	return `${content}\n`;
}

/**
 * Replace an existing managed block without touching the rest of a file.
 *
 * @param {string} existing Current file content.
 * @param {string} block New managed block.
 * @returns {string} Updated content.
 */
function replaceBlock(existing, block) {
	const start = existing.indexOf(START_MARKER);
	const end = existing.indexOf(END_MARKER, start);

	if (!existing.trim()) return `${block}\n`;

	if (start === -1) return `${existing.replace(/\s+$/, '')}\n\n${block}\n`;

	if (end === -1) {
		throw new AgentKitError(
			'Found a start marker without an end marker. Remove the incomplete block and try again.'
		);
	}

	return `${existing.slice(0, start)}${block}${existing.slice(end + END_MARKER.length)}`;
}

/**
 * Write one target and report what happened.
 *
 * @param {AgentTarget} target Target to write.
 * @param {object} options Install options.
 * @param {string} options.cwd Consumer project root.
 * @param {string} options.guide Canonical guide body.
 * @param {string} options.version Package version.
 * @param {boolean} options.force Overwrite dedicated files without markers.
 * @param {boolean} options.dryRun Report without writing.
 * @returns {{ target: AgentTarget, path: string, status: string, detail?: string }} Result for the summary.
 */
function installTarget(target, { cwd, guide, version, force, dryRun }) {
	const absolutePath = join(cwd, target.path);
	const exists = existsSync(absolutePath);
	const current = exists ? readFileSync(absolutePath, 'utf8') : '';
	const rendered = renderTarget(target, guide, version);
	const block = renderBlock(target, guide, version);
	let next = rendered;
	let status = exists ? 'updated' : 'created';
	let detail = '';

	if (target.shared) {
		next = replaceBlock(current, block);
		if (exists) status = current.includes(START_MARKER) ? 'updated' : 'appended';
	} else if (exists && current.includes(START_MARKER)) {
		next = replaceBlock(current, block);
	} else if (exists && !current.includes(START_MARKER)) {
		if (!force) {
			return {
				target,
				path: target.path,
				status: 'skipped',
				detail: 'the file exists without a managed block. Re-run with --force to replace it.'
			};
		}
		status = 'replaced';
	}

	if (dryRun) {
		const labels = {
			created: 'would create',
			updated: 'would update',
			appended: 'would append',
			replaced: 'would replace',
			unchanged: 'unchanged',
			skipped: 'would skip'
		};
		return {
			target,
			path: target.path,
			status: labels[status] ?? status,
			detail
		};
	}

	if (next !== current) {
		mkdirSync(dirname(absolutePath), { recursive: true });
		writeFileSync(absolutePath, next, 'utf8');
	} else {
		status = 'unchanged';
	}

	return { target, path: target.path, status, detail };
}

/**
 * Detect agent configuration files in a project.
 *
 * @param {string} cwd Consumer project root.
 * @returns {TargetName[]} Detected targets in display order.
 */
function detectTargets(cwd) {
	const detected = [];

	if (existsSync(join(cwd, '.claude'))) detected.push('claude');
	if (existsSync(join(cwd, '.cursor')) || existsSync(join(cwd, '.cursorrules'))) {
		detected.push('cursor');
	}
	if (
		existsSync(join(cwd, '.opencode')) ||
		existsSync(join(cwd, 'opencode.json')) ||
		existsSync(join(cwd, 'opencode.jsonc'))
	) {
		detected.push('opencode');
	}
	if (existsSync(join(cwd, '.github', 'copilot-instructions.md'))) detected.push('copilot');
	if (existsSync(join(cwd, '.windsurf'))) detected.push('windsurf');
	if (existsSync(join(cwd, '.clinerules'))) detected.push('cline');
	if (existsSync(join(cwd, 'GEMINI.md'))) detected.push('gemini');
	if (existsSync(join(cwd, 'AGENTS.md'))) detected.push('agents');

	return detected;
}

/**
 * Parse command line arguments.
 *
 * @param {string[]} argv Arguments after the executable name.
 * @returns {{ command: string, subcommand: string, targets: string[], all: boolean, force: boolean, dryRun: boolean, cwd: string, help: boolean }} Parsed options.
 */
function parseArgs(argv) {
	const options = {
		command: argv[0] ?? 'help',
		subcommand: argv[1] ?? '',
		targets: [],
		all: false,
		force: false,
		dryRun: false,
		cwd: process.cwd(),
		help: false
	};

	const start = options.command === 'agents' ? 2 : 1;

	for (let index = start; index < argv.length; index += 1) {
		const argument = argv[index];

		if (argument === '--all') {
			options.all = true;
			continue;
		}
		if (argument === '--force') {
			options.force = true;
			continue;
		}
		if (argument === '--dry-run') {
			options.dryRun = true;
			continue;
		}
		if (argument === '--help' || argument === '-h') {
			options.help = true;
			continue;
		}
		if (argument === '--cwd') {
			const value = argv[index + 1];
			if (!value) throw new AgentKitError('--cwd needs a directory path.');
			options.cwd = resolve(value);
			index += 1;
			continue;
		}
		if (argument.startsWith('--cwd=')) {
			options.cwd = resolve(argument.slice('--cwd='.length));
			continue;
		}
		if (argument === '--tool' || argument === '--target') {
			const value = argv[index + 1];
			if (!value) throw new AgentKitError('--tool needs a target name.');
			options.targets.push(...value.split(','));
			index += 1;
			continue;
		}
		if (argument.startsWith('--tool=') || argument.startsWith('--target=')) {
			options.targets.push(...argument.slice(argument.indexOf('=') + 1).split(','));
			continue;
		}
		if (argument.startsWith('-')) {
			throw new AgentKitError(`Unknown option "${argument}". Run svelte-elevenlabs agents --help.`);
		}

		options.targets.push(...argument.split(','));
	}

	options.targets = [...new Set(options.targets.map((entry) => entry.trim()).filter(Boolean))];
	return options;
}

/**
 * Print command help.
 */
function printHelp() {
	console.log(`svelte-elevenlabs agent kit

Usage:
  svelte-elevenlabs agents list
  svelte-elevenlabs agents install [targets] [--all] [--force] [--dry-run]
  svelte-elevenlabs agents print [target]

Targets:
  ${TARGETS.map((target) => target.name).join(', ')}

Examples:
  svelte-elevenlabs agents install
  svelte-elevenlabs agents install claude cursor opencode
  svelte-elevenlabs agents install --all
  svelte-elevenlabs agents install claude --dry-run
  svelte-elevenlabs agents print cursor

With no target names, the command detects configured agents and falls back to
AGENTS.md. Shared files keep their existing content. Re-running the command
updates only the managed block between the svelte-elevenlabs markers.`);
}

/**
 * Print every target and its destination.
 */
function listTargets() {
	console.log('Available agent targets:\n');
	for (const target of TARGETS) {
		console.log(`  ${target.name.padEnd(9)} ${target.label.padEnd(28)} ${target.path}`);
	}
	console.log('\nUse "svelte-elevenlabs agents install --all" to install every target.');
}

/**
 * Run the agents command.
 *
 * @param {object} options Parsed options.
 */
function runAgents(options) {
	if (
		!options.subcommand ||
		options.subcommand === 'help' ||
		options.subcommand === '--help' ||
		options.subcommand === '-h' ||
		options.help
	) {
		printHelp();
		return;
	}

	const version = readVersion();

	if (options.subcommand === 'list') {
		listTargets();
		return;
	}

	const guide = readGuide();

	if (options.subcommand === 'print') {
		const requested = options.targets[0];
		if (!requested) {
			process.stdout.write(`${guide}\n`);
			return;
		}
		const target = findTarget(requested);
		process.stdout.write(renderTarget(target, guide, version));
		return;
	}

	if (options.subcommand !== 'install') {
		throw new AgentKitError(
			`Unknown agents command "${options.subcommand}". Use list, install, or print.`
		);
	}

	if (!options.cwd || !existsSync(options.cwd) || !statSync(options.cwd).isDirectory()) {
		throw new AgentKitError(`The project directory does not exist: ${options.cwd}`);
	}

	const detected = detectTargets(options.cwd);
	const requested = options.all
		? TARGETS.map((target) => target.name)
		: options.targets.length > 0
			? options.targets.map((name) => findTarget(name).name)
			: detected;

	const selected = requested.length > 0 ? requested : ['agents'];
	const unique = [...new Set(selected)];
	const results = unique.map((name) =>
		installTarget(findTarget(name), {
			cwd: options.cwd,
			guide,
			version,
			force: options.force,
			dryRun: options.dryRun
		})
	);

	console.log(
		`${options.dryRun ? 'Agent kit dry run' : 'Agent kit installed'} for ${results.length} ${
			results.length === 1 ? 'target' : 'targets'
		}:\n`
	);

	for (const result of results) {
		const displayPath = relative(options.cwd, join(options.cwd, result.path)).replaceAll('\\', '/');
		const suffix = result.detail ? ` (${result.detail})` : '';
		console.log(`  ${result.status.padEnd(13)} ${displayPath}${suffix}`);
	}

	if (requested.length === 0) {
		console.log(
			'\nNo agent configuration was detected, so the guide was added to AGENTS.md. Use --all or name a tool to install more targets.'
		);
	}

	if (!options.dryRun) {
		console.log('\nRestart your agent session, then ask it to use svelte-elevenlabs.');
	}
}

/**
 * Entry point with human readable failure handling.
 */
function main() {
	const options = parseArgs(process.argv.slice(2));

	if (options.command === 'help' || options.command === '--help' || options.command === '-h') {
		printHelp();
		return;
	}

	if (options.command !== 'agents') {
		throw new AgentKitError(
			`Unknown command "${options.command}". Use "svelte-elevenlabs agents --help".`
		);
	}

	runAgents(options);
}

process.stdout.on('error', (error) => {
	if (error.code === 'EPIPE') process.exit(0);
	throw error;
});

try {
	main();
} catch (error) {
	if (error instanceof AgentKitError) {
		console.error(`[svelte-elevenlabs] ${error.message}`);
	} else {
		console.error('[svelte-elevenlabs] The agent kit command failed.', error);
	}
	process.exitCode = 1;
}
